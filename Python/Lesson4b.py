# For loops
for index in range(5):
    print(index)

print("print 0 to 100")

for index in range(101):
    print(index)

print("print 50 to 100")
for var in range(50, 101):
    print(var)

print("print 801 to 850")
for var in range(801, 851):
    print(var)

print("print 50 to 100 step 5")
for y in range(50,101, 5):
    print(y)


print("print letters in the word 'Jeddy' ")
name = "Jeddy"
for letter in name:
    print(letter)

