# python lists(mutable)
items = [1,3,2,7,9,4,True,'green','red']

# print all items in the list
print(items)

# selecting number '3' using index values
print(items[1])
print(items[7])
print(items[4])

# print the values from second item to fourth item
print(items[1:4])
print(items[4:7])

# print from the 5th item and above (slicing)
print(items[4:])
print(items[6:])

# print from 7th item backwards
print(items[:6])
print(items[:4])


